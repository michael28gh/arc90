const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../js/app.js'), 'utf8');
const start = source.indexOf('function dlog(');
const end = source.indexOf('function isCompleted(', start);
assert.ok(start >= 0 && end > start);
const state = { log: {} };
const context = { S: state, save() {}, todayKey: () => '2026-09-08' };
vm.runInNewContext(source.slice(start, end), context);
context.setStatus(1, '2026-09-08', 'done');
const first = state.log['2026-09-08'].completedAt[1];
assert.ok(Number.isFinite(Date.parse(first)));
assert.ok(Number.isInteger(state.log['2026-09-08'].completionHours[1]));
context.setStatus(1, '2026-09-08', 'min');
assert.equal(state.log['2026-09-08'].completedAt[1], first);
context.setStatus(1, '2026-09-08', null);
assert.equal(state.log['2026-09-08'].completedAt[1], undefined);
assert.equal(state.log['2026-09-08'].completionHours[1], undefined);
context.setStatus(1, '2026-09-07', 'done');
assert.equal(state.log['2026-09-07'].completedAt[1], undefined);
state.log['2026-09-08'] = [2];
context.setStatus(1, '2026-09-08', 'min');
assert.ok(state.log['2026-09-08'].done.includes(2));
assert.ok(state.log['2026-09-08'].min.includes(1));
assert.ok(state.log['2026-09-08'].completedAt[1]);
console.log('Completion times: real check-offs recorded, reduced target preserves time, undo clears, historical edits never invent times.');
