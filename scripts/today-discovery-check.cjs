const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const app = fs.readFileSync(path.join(__dirname, '../js/app.js'), 'utf8');
const workspace = fs.readFileSync(path.join(__dirname, '../js/daily-workspace.js'), 'utf8');
assert.match(app, /let todayHistoryExpanded = true;/, 'Show the full grid on first visit');
assert.doesNotMatch(app, /function wireScrollFX|wireScrollFX\(\)/, 'The ring must scroll with its content, without independent parallax');
assert.match(app, /\$\{todayTasksPanel\(\)\}/);
const start = workspace.indexOf('function todayTasksPanel()');
const end = workspace.indexOf('\nfunction ', start + 1);
assert.ok(start >= 0 && end > start);
const context = { S: { tasks: [] }, taskRow: t => `<div>${t.title}</div>` };
vm.createContext(context);
vm.runInContext(workspace.slice(start, end), context);
assert.match(context.todayTasksPanel(), /No tasks yet/);
assert.match(context.todayTasksPanel(), /data-act="tab" data-id="plan"/);
context.S.tasks = [1, 2, 3, 4].map(id => ({ id, title: `Task ${id}`, done: false }));
const before = JSON.stringify(context.S.tasks);
const html = context.todayTasksPanel();
assert.match(html, /4 open/);
assert.match(html, /Task 1/);
assert.doesNotMatch(html, /Task 4/);
assert.match(html, /data-planning-act="workspace" data-id="ideas"/);
assert.equal(JSON.stringify(context.S.tasks), before, 'Rendering must not reschedule or mutate tasks');
context.S.tasks.forEach(t => { t.done = true; });
assert.match(context.todayTasksPanel(), /All tasks complete/);
console.log('Today discovery passed: visible grid, stable ring, compact tasks and direct workspace access.');
